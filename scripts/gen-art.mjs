// Writes src/art/registry.ts from assets/art/manifest.json: a static require() for every image, because Metro
// cannot bundle paths built at runtime. Run after adding or replacing art:  npm run art
// Every manifest entry becomes { src, w, h, alt }; entries whose file is missing on disk are skipped with a warning.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const artDir = path.join(root, 'assets', 'art');
const manifest = JSON.parse(readFileSync(path.join(artDir, 'manifest.json'), 'utf8'));
const out = path.join(root, 'src', 'art', 'registry.ts');
const warnings = [];

const q = (s) => JSON.stringify(s);
/** one image entry, or null when the file is not there */
function img(e) {
  if (!e?.file) return null;
  if (!existsSync(path.join(artDir, e.file))) { warnings.push(`missing file: ${e.file}`); return null; }
  const alt = e.alt ? `{ en: ${q(e.alt.en ?? '')}, tr: ${q(e.alt.tr ?? '')} }` : `{ en: '', tr: '' }`;
  return `{ src: require(${q(`../../assets/art/${e.file}`)}), w: ${e.width ?? 0}, h: ${e.height ?? 0}, alt: ${alt} }`;
}
function map(obj, fn, indent = '  ') {
  const rows = [];
  for (const [k, v] of Object.entries(obj ?? {})) {
    const body = fn(v);
    if (body) rows.push(`${indent}${q(k)}: ${body},`);
  }
  return `{\n${rows.join('\n')}\n}`;
}
const layered = (v) => {
  const base = img(v.base);
  if (!base) return null;
  const uv = img(v.uv);
  return uv ? `{ base: ${base}, uv: ${uv} }` : `{ base: ${base} }`;
};
const staged = (v) => {
  const stages = map(v.stages ?? {}, img, '    ');
  return stages === '{\n\n}' ? null : `${stages.replace(/\n}$/, '\n  }')}`;
};

const src = `// GENERATED by scripts/gen-art.mjs from assets/art/manifest.json — do not edit by hand; run \`npm run art\`.
// Metro needs a literal require() per image, so the manifest is turned into this static table.
/* eslint-disable */
import type { ArtImage, Layered, Staged } from './types';

export const portraits: Record<string, Staged> = ${map(manifest.portraits, staged)};

export const witnessPortraits: Record<string, ArtImage> = ${map(manifest.witnessPortraits, img)};

export const scenes: Record<string, Layered> = ${map(manifest.scenes, layered)};

export const closeUps: Record<string, Layered> = ${map(manifest.closeUps, layered)};

export const evidence: Record<string, ArtImage> = ${map(manifest.evidence, img)};

export const covers: Record<string, ArtImage> = ${map(manifest.covers, img)};

export const textures: Record<string, ArtImage> = ${map(manifest.textures, img)};

export const icon: Record<string, ArtImage> = ${map(manifest.icon, img)};

/** wave 4: generic drawings per document type, used when an item has no picture of its own */
export const documents: Record<string, ArtImage> = ${map(manifest.documents, img)};

/** wave 4: generic drawings per lab discipline (autopsy, serology, digital, anpr, …) */
export const labs: Record<string, ArtImage> = ${map(manifest.labs, img)};

/** wave 4: day-report illustrations, keyed "<case art prefix>/<day>" */
export const reports: Record<string, ArtImage> = ${map(manifest.reports, img)};

/** wave 4: night-event illustrations, keyed "<case art prefix>/<night event id>" */
export const nights: Record<string, ArtImage> = ${map(manifest.nights, img)};
`;

writeFileSync(out, src);
for (const w of warnings) console.warn(`gen-art: ${w}`);
const count = (src.match(/require\(/g) ?? []).length;
console.log(`gen-art: ${count} images → ${path.relative(root, out).replace(/\\/g, '/')}`);
